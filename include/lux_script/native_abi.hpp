#pragma once
#include <cstdint>
#include <vector>

namespace lux_script {

// The boundary of the ABI between the `lux` binary and the library produced
// by --native (Phase 2): any function compiled natively, regardless of its
// arity or which of the three primitive types each parameter uses, is
// exported with this same fixed signature. This way dlsym() and the VM
// don't need to know the real signature of each function -- the generated
// C++ itself (see native_gen.cpp) packs and unpacks it.
//
// It's a deliberately simple POD: it's defined separately, with the exact
// same text, in the .cpp generated by native_gen.cpp (see
// native_gen.cpp::abi_prelude()) and here -- dlopen doesn't share headers
// between the binary and the loaded library, only an ABI compatible at link
// time, and two textually identical definitions of a POD type are that.
struct NativeValue {
    // Error: the native function detected something that in the VM is a
    // controlled error (division by zero, "% by zero"...), not a crash --
    // see the comment about lux_native_fail() in native_gen.cpp. The
    // message doesn't travel inside NativeValue itself (there's no room in
    // an 8-byte union) but in a per-thread buffer inside the library, read
    // with ErrorMessageFn right after receiving this tag.
    enum class Tag : int32_t { Int, Float, Bool, Error } tag = Tag::Int;
    union {
        int64_t i;
        double  d;
        bool    b;
    };
};

// Unique signature of any already-loaded --native function: the arguments
// come packed in `args[0..argc)`, in the same order as the Lux parameters;
// the result is a single NativeValue.
using CompiledFn = NativeValue (*)(const NativeValue*, int32_t);

// Fixed symbol exported by every --native library (see
// native_gen.cpp::error_runtime_prelude()): the message corresponding to
// the last NativeValue::Tag::Error returned on the calling thread, valid
// until the next native call on that same thread -- whoever reads it must
// copy it into their own std::string before making any other native call.
using ErrorMessageFn = const char* (*)();

// What the VM needs to dispatch a call to native code: the table of
// invocation pointers (indexed by FnSig::index, same as FunctionTable) and
// the error message accessor. A lightweight value, built at each call site
// from a NativeModule (see native_build.hpp) -- it owns nothing, it only
// points.
struct NativeDispatch {
    const std::vector<CompiledFn>* funcs         = nullptr;
    ErrorMessageFn                 error_message = nullptr;
};

} // namespace lux_script
